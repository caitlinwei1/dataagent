#!/usr/bin/env python3
"""Generate gbi-agent's row-level policy file from the dataset metadata.

Each business table gets at most one owning data dimension:
  - direct:  the table has warehouse_id (dimension "warehouse") or shop_id ("shop"); warehouse wins if both
  - derived: the table reaches a direct table through logical foreign keys (order_id -> trd_order ...),
             so the filter is an IN-subquery on the parent; multi-hop chains nest
Tables reaching neither (catalog, members, regions, dates ...) are shared reference data: no row filter.
Two hand-written overrides cover columns the naming rule cannot see (wms_transfer has from/to warehouse).

Usage: python3 scripts/security/gen_row_policies.py > gbi-agent/src/main/resources/data-permission/row-policies.yml
"""
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
tables = json.load(open(os.path.join(ROOT, 'dataset/metadata/tables.json')))
rels = json.load(open(os.path.join(ROOT, 'dataset/metadata/logical_relations.json')))
cols = {t['name']: {c['name'] for c in t['columns']} for t in tables}
pk = {t['name']: t.get('primary_key') or 'id' for t in tables}

OVERRIDES = {
    'wms_transfer': ('warehouse', 'from_warehouse_id IN (:warehouse) OR to_warehouse_id IN (:warehouse)'),
}

policy = {}
for t in tables:
    n = t['name']
    if n in OVERRIDES:
        policy[n] = OVERRIDES[n]
    elif 'warehouse_id' in cols[n]:
        policy[n] = ('warehouse', 'warehouse_id IN (:warehouse)')
    elif 'shop_id' in cols[n]:
        policy[n] = ('shop', 'shop_id IN (:shop)')

# derived: repeat until no change, so chains (trd_refund_item -> trd_refund -> trd_order) resolve
changed = True
while changed:
    changed = False
    for r in rels:
        child, parent = r['table'], r['ref_table']
        if child in policy or parent not in policy or child == parent:
            continue
        # only follow edges that point at the parent's key (child rows belong to one parent row)
        if r['ref_column'] != pk[parent]:
            continue
        # skip reference-data edges: a member / sku / region does not "own" the child row
        if parent.startswith(('dim_', 'usr_', 'prd_', 'mkt_')) and parent not in ('prd_bundle',):
            continue
        dim, pf = policy[parent]
        policy[child] = (dim, f"{r['column']} IN (SELECT {r['ref_column']} FROM {parent} WHERE {pf})")
        changed = True

out = sys.stdout
out.write('# Generated by scripts/security/gen_row_policies.py from dataset/metadata. Do not edit by hand.\n')
out.write('# table -> owning dimension + filter; ":dim" expands to the user\'s allowed values for that dimension.\n')
out.write('# Tables not listed are shared reference data (catalog, members, regions, dates): no row filter.\n')
out.write('dimensions:\n  shop: number\n  warehouse: number\n')
out.write('tables:\n')
for n in sorted(policy):
    dim, f = policy[n]
    out.write(f'  {n}:\n    dim: {dim}\n    filter: "{f}"\n')
print(f'{len(policy)} tables with a row policy, {len(tables) - len(policy)} shared', file=sys.stderr)
