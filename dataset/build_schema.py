"""Generate DDL (full / partial comments), M-Schema text, table catalog and logical relations
from dataset/schema/tables.py.

Usage: python3 dataset/build_schema.py
Outputs:
  dataset/ddl/mysql_full.sql      every table/column commented
  dataset/ddl/mysql_partial.sql   ablate=True tables have no comments (注释消融)
  dataset/metadata/mschema_full.txt / mschema_partial.txt   XiYan-style M-Schema
  dataset/metadata/tables.json    catalog: name, domain, comment, ablate, columns, fks
  dataset/metadata/logical_relations.json   FK list for DataAgent logical-relations API
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "schema"))
from tables import TABLES  # noqa: E402
from extra_columns import EXTRA, audit_for  # noqa: E402

DB = "gbi_ecommerce"
TYPES = {
    "id": "BIGINT NOT NULL AUTO_INCREMENT",
    "b": "BIGINT",
    "i": "INT",
    "t": "TINYINT",
    "s": "VARCHAR(64)",
    "l": "VARCHAR(255)",
    "d": "DECIMAL(14,2)",
    "r": "DECIMAL(12,6)",
    "dt": "DATE",
    "ts": "DATETIME",
}
MSCHEMA_TYPES = {"id": "BIGINT", "b": "BIGINT", "i": "INT", "t": "TINYINT", "s": "VARCHAR",
                 "l": "VARCHAR", "d": "DECIMAL", "r": "DECIMAL", "dt": "DATE", "ts": "DATETIME"}


def parse(table):
    cols, fks = [], []
    specs = [(s, "core") for s in table["cols"]] + [(s, "extra") for s in EXTRA[table["name"]]] + \
        [(s, "audit") for s in audit_for(table["name"])]
    for spec, kind in specs:
        parts = spec.split(" ")
        name, typ = parts[0], parts[1]
        rest = parts[2:]
        fk, enum = None, None
        if rest and rest[-1].startswith("->"):
            fk = rest.pop()[2:]
        if rest and rest[-1].startswith("{"):
            enum = rest.pop().strip("{}").split("|")
        comment = " ".join(rest)
        if enum:
            comment += "：" + "/".join(enum)
        cols.append(dict(name=name, type=typ, comment=comment, kind=kind, enum=enum))
        if fk:
            rt, rc = fk.split(".")
            fks.append(dict(table=table["name"], column=name, ref_table=rt, ref_column=rc))
    pk = cols[0]["name"]
    return cols, fks, pk


def q(s):
    return s.replace("'", "''")


def ddl(partial):
    out = [f"-- {DB}: 86 tables, {'partial' if partial else 'full'} comments. Generated by build_schema.py",
           f"CREATE DATABASE IF NOT EXISTS {DB} DEFAULT CHARACTER SET utf8mb4;", f"USE {DB};", ""]
    for t in TABLES:
        cols, fks, pk = parse(t)
        strip = partial and t["ablate"]
        lines = []
        for c in cols:
            typ = TYPES[c["type"]]
            if c["name"] == pk and c["type"] != "id":
                typ += " NOT NULL"
            cm = "" if strip else f" COMMENT '{q(c['comment'])}'"
            lines.append(f"  `{c['name']}` {typ}{cm}")
        lines.append(f"  PRIMARY KEY (`{pk}`)")
        lines += [f"  KEY `idx_{f['column']}` (`{f['column']}`)" for f in fks]
        tc = "" if strip else f" COMMENT='{q(t['comment'])}'"
        out.append(f"DROP TABLE IF EXISTS `{t['name']}`;")
        out.append(f"CREATE TABLE `{t['name']}` (\n" + ",\n".join(lines) + f"\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4{tc};\n")
    return "\n".join(out)


PG_TYPES = {"id": "BIGINT", "b": "BIGINT", "i": "INTEGER", "t": "SMALLINT", "s": "VARCHAR(64)", "l": "VARCHAR(255)",
            "d": "NUMERIC(14,2)", "r": "NUMERIC(12,6)", "dt": "DATE", "ts": "TIMESTAMP"}


def ddl_pg(partial):
    """PostgreSQL / Hologres-compatible DDL (schema gbi_ecommerce)."""
    out = [f"-- {DB}: 86 tables for PostgreSQL (also used as the Hologres stand-in). Generated by build_schema.py",
           f"DROP SCHEMA IF EXISTS {DB} CASCADE;\n" f"CREATE SCHEMA {DB};", f"SET search_path TO {DB};", ""]
    for t in TABLES:
        cols, fks, pk = parse(t)
        strip = partial and t["ablate"]
        lines = [f"  {c['name']} {PG_TYPES[c['type']]}" + (" NOT NULL" if c["name"] == pk else "") for c in cols]
        lines.append(f"  PRIMARY KEY ({pk})")
        out.append(f"DROP TABLE IF EXISTS {t['name']};")
        out.append(f"CREATE TABLE {t['name']} (\n" + ",\n".join(lines) + "\n);")
        out += [f"CREATE INDEX idx_{t['name']}_{f['column']} ON {t['name']} ({f['column']});" for f in fks]
        if not strip:
            out.append(f"COMMENT ON TABLE {t['name']} IS '{q(t['comment'])}';")
            out += [f"COMMENT ON COLUMN {t['name']}.{c['name']} IS '{q(c['comment'])}';" for c in cols]
        out.append("")
    return "\n".join(out)


def mschema(partial):
    out = [f"【DB_ID】 {DB}", "【Schema】"]
    all_fks = []
    for t in TABLES:
        cols, fks, pk = parse(t)
        strip = partial and t["ablate"]
        all_fks += fks
        out.append(f"# Table: {t['name']}" + ("" if strip else f", {t['comment']}"))
        out.append("[")
        items = []
        for c in cols:
            bits = [f"{c['name']}:{MSCHEMA_TYPES[c['type']]}"]
            if c["name"] == pk:
                bits.append("Primary Key")
            if not strip and c["comment"]:
                bits.append(c["comment"])
            items.append("(" + ", ".join(bits) + ")")
        out.append(",\n".join(items))
        out.append("]")
    out.append("【Foreign keys】")
    out += [f"{f['table']}.{f['column']}={f['ref_table']}.{f['ref_column']}" for f in all_fks]
    return "\n".join(out) + "\n"


def main():
    names = {t["name"] for t in TABLES}
    catalog, rels = [], []
    for t in TABLES:
        cols, fks, pk = parse(t)
        for f in fks:
            assert f["ref_table"] in names, f
            ref = next(x for x in TABLES if x["name"] == f["ref_table"])
            assert f["ref_column"] in [c["name"] for c in parse(ref)[0]], f
        catalog.append(dict(name=t["name"], domain=t["domain"], comment=t["comment"], ablate=t["ablate"],
                            primary_key=pk, columns=cols, foreign_keys=fks))
        rels += fks
    os.makedirs(os.path.join(HERE, "ddl"), exist_ok=True)
    os.makedirs(os.path.join(HERE, "metadata"), exist_ok=True)
    for partial, tag in ((False, "full"), (True, "partial")):
        open(os.path.join(HERE, "ddl", f"mysql_{tag}.sql"), "w").write(ddl(partial))
        open(os.path.join(HERE, "ddl", f"postgres_{tag}.sql"), "w").write(ddl_pg(partial))
        open(os.path.join(HERE, "metadata", f"mschema_{tag}.txt"), "w").write(mschema(partial))
    json.dump(catalog, open(os.path.join(HERE, "metadata", "tables.json"), "w"), ensure_ascii=False, indent=1)
    json.dump(rels, open(os.path.join(HERE, "metadata", "logical_relations.json"), "w"), ensure_ascii=False, indent=1)
    by = {}
    for t in TABLES:
        by.setdefault(t["domain"], [0, 0])
        by[t["domain"]][0] += 1
        by[t["domain"]][1] += t["ablate"]
    print("tables", len(TABLES), "fks", len(rels), "columns", sum(len(c["columns"]) for c in catalog))
    for d, (n, a) in by.items():
        print(f"  {d}: {n} tables, {a} ablated")


if __name__ == "__main__":
    main()
