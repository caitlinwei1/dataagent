DIMENSION = {"dim_region", "dim_shop", "dim_store", "dim_date", "dim_currency", "dim_platform"}


def audit_for(table):
    cols = list(AUDIT)
    if table in APPEND_ONLY:
        cols = [c for c in cols if not c.startswith(("updated_time", "is_deleted"))]
    if table in DIMENSION:
        cols = [c for c in cols if not c.startswith(("created_by", "is_deleted"))]
    return cols


