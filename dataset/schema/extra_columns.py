"""Additional columns that bring the schema to realistic width (target: 1,146 fields).

AUDIT columns are appended to every table. EXTRA adds business columns per table.
A trailing {A|B|C} token lists enum values used by the seed filler (and by enum-value recall);
it is stripped from the DDL comment, which instead lists the values after a colon.
Numeric/date columns without a token are filled by type-based rules in fill_extra.py.
"""

# Append-only tables (流水/日汇总/快照) skip updated_time + is_deleted; dimension tables skip created_by + is_deleted.
